-- 330: listas de conteo del Inventario (ERP). Pedido del dueño, 2026-11-19: «que puedan hacer conteos de inventario:
-- buscar por proveedor, SKU, nombre y categoría; irán agregando a una lista los productos que tienen y ahí meten la
-- existencia. Primero crean la lista de todo el material que tienen y ponen cuánto tienen de cada uno».
--
-- Qué añade (solo el Inventario del ERP; el conteo formal de Almacén, 274, no se toca):
--   · erp.count_lists       — una lista por tienda: nombre, estado (open → submitted), quién la creó y cuándo se cambió.
--   · erp.count_list_lines  — un renglón por producto (único por lista). `counted_qty` NULL = todavía no contado.
--   · Funciones (SECURITY DEFINER, search_path vacío) que son la ÚNICA vía de escritura: crear, agregar productos,
--     fijar la cantidad contada, quitar un renglón, enviar, y las dos lecturas (detalle y listado).
--   · Enviar una lista llama a erp.record_cycle_count por cada renglón contado: el conteo entra por la ruta EXISTENTE,
--     así que la tabla de revisión / conciliación (erp.cycle_counts) sigue igual. Todo en una sola transacción: si un
--     renglón falla, no se registra ninguno.
--
-- Quién: el mismo nivel que ya puede contar en el Inventario, `erp.current_app_role()` en ('admin','manager') — lo
-- mismo que record_cycle_count, list_cycle_counts y la página /erp/inventory (canSeeCost). No se amplía a staff.
--
-- Lo que NO hace:
--   · No hay índices nuevos: el catálogo son unos 6.5 mil productos y el buscador es ILIKE sobre la vista; un recorrido
--     secuencial es de milisegundos. Si el conteo se vuelve lento, el sitio es erp.products(sku)/(mpn), con trigramas.
--   · La cantidad sistema (qoh) NO se guarda en el renglón: se lee de erp.store_products al mostrarla, y solo para los
--     renglones ya contados (así la pantalla no le enseña al contador la existencia antes de que cuente). Al enviar, la
--     diferencia la fija record_cycle_count con la existencia de ese momento.
--   · Dos personas editando el mismo renglón: gana el último guardado (no hay bloqueo por renglón en la pantalla).
--
-- Idempotente: create ... if not exists, create or replace, políticas con drop ... if exists, grants repetibles.
-- Para deshacer: drop function erp.count_list_* / erp.count_lists_list; drop table erp.count_list_lines, erp.count_lists;
-- y delete from public.schema_migrations where name = '330_listas_de_conteo.sql'.

-- ---------------------------------------------------------------------------
-- 1. Tablas
-- ---------------------------------------------------------------------------
create table if not exists erp.count_lists (
  id           bigint generated by default as identity primary key,
  store_id     text not null references erp.stores(id),
  name         text not null check (char_length(btrim(name)) between 1 and 120),
  status       text not null default 'open' check (status in ('open', 'submitted')),
  created_by   uuid references public.profiles(id) on delete set null,
  created_at   timestamptz not null default now(),
  updated_by   uuid references public.profiles(id) on delete set null,
  updated_at   timestamptz not null default now(),
  submitted_by uuid references public.profiles(id) on delete set null,
  submitted_at timestamptz,
  constraint count_lists_submitted_consistent check ((status = 'submitted') = (submitted_at is not null))
);

create table if not exists erp.count_list_lines (
  id             bigint generated by default as identity primary key,
  list_id        bigint not null references erp.count_lists(id) on delete cascade,
  product_id     bigint not null references erp.products(id),
  counted_qty    numeric check (counted_qty is null or counted_qty >= 0),
  counted_by     uuid references public.profiles(id) on delete set null,
  counted_at     timestamptz,
  cycle_count_id bigint references erp.cycle_counts(id),
  added_by       uuid references public.profiles(id) on delete set null,
  created_at     timestamptz not null default now(),
  constraint count_list_lines_list_product_key unique (list_id, product_id),
  constraint count_list_lines_counted_consistent check ((counted_qty is null) = (counted_at is null))
);

create index if not exists count_list_lines_product_idx on erp.count_list_lines (product_id);
create index if not exists count_lists_recent_idx on erp.count_lists (status, updated_at desc);

-- ---------------------------------------------------------------------------
-- 2. RLS: el gate del módulo (restrictivo) + lectura para admin/manager. Ninguna política de escritura: todo entra por
--    las funciones de abajo.
-- ---------------------------------------------------------------------------
alter table erp.count_lists enable row level security;
alter table erp.count_list_lines enable row level security;

drop policy if exists "erp module gate" on erp.count_lists;
create policy "erp module gate" on erp.count_lists as restrictive for all to authenticated
  using ((select public.has_erp_access())) with check ((select public.has_erp_access()));
drop policy if exists "erp module gate" on erp.count_list_lines;
create policy "erp module gate" on erp.count_list_lines as restrictive for all to authenticated
  using ((select public.has_erp_access())) with check ((select public.has_erp_access()));

drop policy if exists "count_lists read (mgr/admin)" on erp.count_lists;
create policy "count_lists read (mgr/admin)" on erp.count_lists as permissive for select to authenticated
  using ((select erp.current_app_role()) = any (array['admin', 'manager']));
drop policy if exists "count_list_lines read (mgr/admin)" on erp.count_list_lines;
create policy "count_list_lines read (mgr/admin)" on erp.count_list_lines as permissive for select to authenticated
  using ((select erp.current_app_role()) = any (array['admin', 'manager']));

-- Grants: la 067 da «all» a authenticated por defecto en todo el esquema; aquí se reduce a lectura.
revoke all on erp.count_lists, erp.count_list_lines from anon, public;
grant select on erp.count_lists, erp.count_list_lines to authenticated;
revoke insert, update, delete, truncate on erp.count_lists, erp.count_list_lines from authenticated;
grant all on erp.count_lists, erp.count_list_lines to service_role;

-- ---------------------------------------------------------------------------
-- 3. Puerta común: admin o manager del ERP (la misma que record_cycle_count).
-- ---------------------------------------------------------------------------
create or replace function erp.count_list_gate()
  returns void language plpgsql stable security definer set search_path = '' as $$
begin
  if coalesce(erp.current_app_role()::text, '') not in ('admin', 'manager') then
    raise exception 'not authorized' using errcode = '42501';
  end if;
end $$;

-- ---------------------------------------------------------------------------
-- 4. Crear una lista
-- ---------------------------------------------------------------------------
create or replace function erp.count_list_create(p_store_id text, p_name text)
  returns bigint language plpgsql security definer set search_path = '' as $$
declare v_id bigint; v_name text := btrim(coalesce(p_name, ''));
begin
  perform erp.count_list_gate();
  if char_length(v_name) < 1 or char_length(v_name) > 120 then
    raise exception 'LIST_NAME_INVALID' using errcode = 'P0001';
  end if;
  if p_store_id is null or not exists (select 1 from erp.stores s where s.id = p_store_id) then
    raise exception 'store % not found', p_store_id using errcode = 'P0002';
  end if;
  insert into erp.count_lists (store_id, name, created_by, updated_by)
  values (p_store_id, v_name, auth.uid(), auth.uid())
  returning id into v_id;
  return v_id;
end $$;

-- ---------------------------------------------------------------------------
-- 5. Agregar productos (un lote de hasta 200; los que ya están no se duplican)
-- ---------------------------------------------------------------------------
create or replace function erp.count_list_add_products(p_list_id bigint, p_product_ids bigint[])
  returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_status text; v_added int := 0; v_ids bigint[];
begin
  perform erp.count_list_gate();
  select status into v_status from erp.count_lists where id = p_list_id for update;
  if not found then raise exception 'LIST_NOT_FOUND' using errcode = 'P0002'; end if;
  if v_status <> 'open' then raise exception 'LIST_CLOSED' using errcode = 'P0001'; end if;
  v_ids := coalesce(p_product_ids, '{}');
  if cardinality(v_ids) > 200 then raise exception 'LIST_TOO_MANY' using errcode = 'P0001'; end if;
  if cardinality(v_ids) > 0 then
    insert into erp.count_list_lines (list_id, product_id, added_by)
    select distinct p_list_id, p.id, auth.uid()
      from erp.products p
     where p.id = any (v_ids)
    on conflict (list_id, product_id) do nothing;
    get diagnostics v_added = row_count;
    update erp.count_lists set updated_at = now(), updated_by = auth.uid() where id = p_list_id;
  end if;
  return jsonb_build_object('added', v_added);
end $$;

-- ---------------------------------------------------------------------------
-- 6. Fijar la cantidad contada de un renglón (NULL = borrarla; vuelve a «sin contar»)
-- ---------------------------------------------------------------------------
create or replace function erp.count_list_lines_json(p_list_id bigint, p_line_id bigint)
  returns jsonb language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_agg(s.x order by s.id), '[]'::jsonb) from (
    select ln.id,
      jsonb_build_object(
        'id', ln.id,
        'product_id', p.id,
        'sku', p.sku,
        'name', p.name,
        'vendor_name', v.name,
        'category_path', c.path,
        'base_unit', p.base_unit,
        'counted_qty', ln.counted_qty,
        'counted_at', ln.counted_at,
        'counted_by_name', pr.full_name,
        'cycle_count_id', ln.cycle_count_id,
        -- La existencia del sistema solo sale para los renglones ya contados (no sesga el conteo). Ya enviada la
        -- lista, sale la que quedó registrada en el conteo.
        'system_qty', case when ln.counted_qty is null then null
                           else coalesce(cc.system_qty, sp.qoh, 0) end
      ) as x
      from erp.count_list_lines ln
      join erp.count_lists l on l.id = ln.list_id
      join erp.products p on p.id = ln.product_id
      left join erp.vendors v on v.id = p.vendor_id
      left join erp.categories c on c.id = p.category_id
      left join erp.store_products sp on sp.store_id = l.store_id and sp.product_id = p.id
      left join erp.cycle_counts cc on cc.id = ln.cycle_count_id
      left join public.profiles pr on pr.id = ln.counted_by
     where ln.list_id = p_list_id
       and (p_line_id is null or ln.id = p_line_id)
  ) s
$$;

create or replace function erp.count_list_set_qty(p_line_id bigint, p_counted_qty numeric)
  returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_list bigint; v_status text;
begin
  perform erp.count_list_gate();
  if p_counted_qty is not null and p_counted_qty < 0 then raise exception 'QTY_INVALID' using errcode = 'P0001'; end if;
  -- Primero la lista y luego el renglón: el mismo orden que enviar, para que no se traben entre sí.
  select ln.list_id into v_list from erp.count_list_lines ln where ln.id = p_line_id;
  if not found then raise exception 'LINE_NOT_FOUND' using errcode = 'P0002'; end if;
  select l.status into v_status from erp.count_lists l where l.id = v_list for update;
  if v_status <> 'open' then raise exception 'LIST_CLOSED' using errcode = 'P0001'; end if;
  perform 1 from erp.count_list_lines ln where ln.id = p_line_id for update;
  update erp.count_list_lines
     set counted_qty = p_counted_qty,
         counted_by  = case when p_counted_qty is null then null else auth.uid() end,
         counted_at  = case when p_counted_qty is null then null else now() end
   where id = p_line_id;
  update erp.count_lists set updated_at = now(), updated_by = auth.uid() where id = v_list;
  return erp.count_list_lines_json(v_list, p_line_id) -> 0;
end $$;

-- ---------------------------------------------------------------------------
-- 7. Quitar un renglón
-- ---------------------------------------------------------------------------
create or replace function erp.count_list_remove_line(p_line_id bigint)
  returns void language plpgsql security definer set search_path = '' as $$
declare v_list bigint; v_status text;
begin
  perform erp.count_list_gate();
  select ln.list_id into v_list from erp.count_list_lines ln where ln.id = p_line_id;
  if not found then raise exception 'LINE_NOT_FOUND' using errcode = 'P0002'; end if;
  select l.status into v_status from erp.count_lists l where l.id = v_list for update;
  if v_status <> 'open' then raise exception 'LIST_CLOSED' using errcode = 'P0001'; end if;
  delete from erp.count_list_lines where id = p_line_id;
  update erp.count_lists set updated_at = now(), updated_by = auth.uid() where id = v_list;
end $$;

-- ---------------------------------------------------------------------------
-- 8. Enviar: cada renglón contado entra por erp.record_cycle_count; la lista queda de solo lectura.
-- ---------------------------------------------------------------------------
create or replace function erp.count_list_submit(p_list_id bigint)
  returns jsonb language plpgsql security definer set search_path = '' as $$
declare l erp.count_lists%rowtype; r record; v_cc bigint; v_n int := 0;
begin
  perform erp.count_list_gate();
  select * into l from erp.count_lists where id = p_list_id for update;
  if not found then raise exception 'LIST_NOT_FOUND' using errcode = 'P0002'; end if;
  if l.status <> 'open' then raise exception 'LIST_CLOSED' using errcode = 'P0001'; end if;
  if not exists (select 1 from erp.count_list_lines where list_id = p_list_id) then
    raise exception 'LIST_EMPTY' using errcode = 'P0001';
  end if;
  if exists (select 1 from erp.count_list_lines where list_id = p_list_id and counted_qty is null) then
    raise exception 'LIST_HAS_UNCOUNTED' using errcode = 'P0001';
  end if;
  for r in
    select id, product_id, counted_qty from erp.count_list_lines where list_id = p_list_id order by id
  loop
    v_cc := (erp.record_cycle_count(r.product_id, l.store_id, r.counted_qty, null) ->> 'count_id')::bigint;
    update erp.count_list_lines set cycle_count_id = v_cc where id = r.id;
    v_n := v_n + 1;
  end loop;
  update erp.count_lists
     set status = 'submitted', submitted_by = auth.uid(), submitted_at = now(),
         updated_at = now(), updated_by = auth.uid()
   where id = p_list_id;
  return jsonb_build_object('recorded', v_n);
end $$;

-- ---------------------------------------------------------------------------
-- 9. Lecturas: detalle de una lista y listado (abiertas primero, luego por último cambio)
-- ---------------------------------------------------------------------------
create or replace function erp.count_list_detail(p_list_id bigint)
  returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare v_list jsonb;
begin
  perform erp.count_list_gate();
  select jsonb_build_object(
      'id', l.id, 'store_id', l.store_id, 'store_name', s.name, 'name', l.name, 'status', l.status,
      'created_at', l.created_at, 'created_by_name', pc.full_name,
      'updated_at', l.updated_at, 'updated_by_name', pu.full_name,
      'submitted_at', l.submitted_at, 'submitted_by_name', ps.full_name)
    into v_list
    from erp.count_lists l
    left join erp.stores s on s.id = l.store_id
    left join public.profiles pc on pc.id = l.created_by
    left join public.profiles pu on pu.id = l.updated_by
    left join public.profiles ps on ps.id = l.submitted_by
   where l.id = p_list_id;
  if v_list is null then raise exception 'LIST_NOT_FOUND' using errcode = 'P0002'; end if;
  return jsonb_build_object('list', v_list, 'lines', erp.count_list_lines_json(p_list_id, null));
end $$;

create or replace function erp.count_lists_list(p_limit integer default 50, p_offset integer default 0)
  returns jsonb language plpgsql stable security definer set search_path = '' as $$
begin
  perform erp.count_list_gate();
  return coalesce((
    select jsonb_agg(s.x order by s.abierta desc, s.updated_at desc, s.id desc) from (
      select l.id, l.updated_at, (l.status = 'open') as abierta,
        jsonb_build_object(
          'id', l.id, 'store_id', l.store_id, 'store_name', st.name, 'name', l.name, 'status', l.status,
          'created_at', l.created_at, 'created_by_name', pc.full_name,
          'updated_at', l.updated_at, 'submitted_at', l.submitted_at, 'submitted_by_name', ps.full_name,
          'lines', (select count(*) from erp.count_list_lines ln where ln.list_id = l.id),
          'counted', (select count(*) from erp.count_list_lines ln where ln.list_id = l.id and ln.counted_qty is not null)
        ) as x
        from erp.count_lists l
        left join erp.stores st on st.id = l.store_id
        left join public.profiles pc on pc.id = l.created_by
        left join public.profiles ps on ps.id = l.submitted_by
       order by (l.status = 'open') desc, l.updated_at desc, l.id desc
       limit least(greatest(coalesce(p_limit, 50), 1), 200)
      offset greatest(coalesce(p_offset, 0), 0)
    ) s
  ), '[]'::jsonb);
end $$;

