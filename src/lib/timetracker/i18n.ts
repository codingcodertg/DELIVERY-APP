let lang: "en" | "es" = ((): "en" | "es" => {
  try { return (localStorage.getItem("tt_lang") as "en" | "es") || "en"; } catch { return "en"; }
})();
const subs = new Set<(l: "en" | "es") => void>();

export function getLang(): "en" | "es" { return lang; }
export function setLang(l: "en" | "es"): void {
  lang = l;
  try { localStorage.setItem("tt_lang", l); } catch { /* ignore */ }
  subs.forEach((f) => f(l));
}
export function t(key: string, vars?: Record<string, string | number>): string {
  let s = (DICT[lang] && DICT[lang][key]) ?? DICT.en[key] ?? key;
  // `\w`, no `w`. La barra se había perdido en algún copiado y el patrón casaba con la letra
  // w literal, así que NINGUNA de las 99 cadenas con variables sustituía nada: se enseñaba
  // "{h} h restantes" tal cual, en los dos idiomas (D-122).
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
  return s;
}
export function useT(): typeof t {
  const [, force] = useState(lang);
  useEffect(() => { const f = (l: "en" | "es") => force(l); subs.add(f); return () => { subs.delete(f); }; }, []);
  return t;
}
